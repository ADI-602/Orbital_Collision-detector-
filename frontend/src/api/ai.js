/**
 * ai.js — POST /api/ai/advise (backend/api/main.py:303-309).
 *
 * The AI layer never computes a physics number. It receives already-computed
 * pipeline output as structured JSON and returns narrative only. Everything
 * it says must be rendered in the UI as commentary ON a number the physics
 * panel already displays — never as the source of that number.
 *
 * PROVIDER-AGNOSTIC BY DESIGN. The frontend must not name or assume a
 * provider. The backend docstrings that disagreed with advisor.py were
 * corrected on 2026-09-22 (they said ANTHROPIC_API_KEY; the code has always
 * read GEMINI_API_KEY/GOOGLE_API_KEY), but the rule stands regardless of
 * which provider is wired up: we trust only the response shape and the
 * is_fallback flag.
 *
 * THIS ENDPOINT ALWAYS RETURNS 200. Failures degrade to a deterministic
 * rule-based advisor rather than erroring, so HTTP status tells you nothing
 * about whether a live model answered.
 *
 * CONSUMING RULE — render "AI: LIVE" only when `is_fallback === false`
 * exactly. `true`, missing, or any non-boolean must render as fallback or
 * unknown. Defaulting the other way would present rule-based text as live AI
 * output, which is precisely the fabrication CLAUDE.md 1.3 forbids.
 *
 * Note also that the server never calls load_dotenv, so `is_fallback` is
 * true in local dev unless GEMINI_API_KEY is exported into the uvicorn
 * process environment.
 */

import { post } from './client.js'

/**
 * Physics output handed across the boundary (backend/ai/schema.py:12-21).
 * @typedef {object} ConjunctionContext
 * @property {string} primary_name
 * @property {string} secondary_name
 * @property {string} tca_iso              NOTE: not `tca_utc_iso` as physics returns
 * @property {number} miss_distance_m
 * @property {number} pre_burn_pc
 * @property {number} [relative_speed_km_s] server default 9.8
 * @property {number} [primary_alt_km]      server default 790.0
 * @property {number} [hard_body_radius_m]  server default 14.5 (METRES)
 */

/**
 * One pre-computed burn option (backend/ai/schema.py:24-32).
 * Every field is required — there are no server-side defaults.
 * @typedef {object} ManeuverOption
 * @property {number} delta_v_cm_s
 * @property {number} lead_time_minutes
 * @property {number} post_burn_miss_distance_m
 * @property {number} post_burn_pc
 * @property {number} risk_reduction_pct
 * @property {number} fuel_consumed_kg
 * @property {boolean} recommended        NOTE: not `maneuver_recommended`
 */

/**
 * @typedef {object} AiAdvisorResponse
 * @property {string} executive_summary
 * @property {string} risk_assessment
 * @property {string} recommended_action
 * @property {string} tradeoff_analysis
 * @property {Record<string, unknown>} key_metrics untyped on the wire; in
 *   fallback mode it carries pre_burn_pc, post_burn_pc, risk_reduction_pct,
 *   fuel_consumed_kg, recommended_burn_delta_v_cm_s, maneuver_required
 *   (advisor.py:84-91). In live mode it is whatever the model returned —
 *   never index it blindly.
 * @property {boolean} is_fallback true when generated by the deterministic
 *   offline advisor rather than a live model.
 */

const ADVISE_TIMEOUT_MS = 60000

/**
 * True only when a live model produced this response. Anything ambiguous —
 * a missing flag, a non-boolean — is treated as fallback.
 *
 * @param {AiAdvisorResponse | null | undefined} response
 * @returns {boolean}
 */
export function isLiveAdvice(response) {
  return response?.is_fallback === false
}

/**
 * @param {object} body
 * @param {ConjunctionContext} body.conjunction
 * @param {ManeuverOption[]} [body.maneuvers] server default []
 * @param {string} [body.query_type] "explanation" | "tradeoff" | "recommendation"
 * @param {import('./types.js').ApiRequestOptions} [opts]
 * @returns {Promise<AiAdvisorResponse>}
 */
export function getAiAdvice(body, opts = {}) {
  return post(
    '/api/ai/advise',
    { query_type: 'recommendation', maneuvers: [], ...body },
    { timeoutMs: ADVISE_TIMEOUT_MS, ...opts },
  )
}
