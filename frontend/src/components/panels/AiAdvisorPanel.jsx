import ErrorState from '../common/ErrorState.jsx'
import LoadingState from '../common/LoadingState.jsx'
import PendingRegion from '../common/PendingRegion.jsx'
import './AiAdvisorPanel.css'

/**
 * AiAdvisorPanel — the narrative layer, and the visible edge of the
 * physics/AI boundary.
 *
 * ========================= WHAT THIS PANEL IS =========================
 * Commentary on numbers the physics panels already display. The advisor is
 * handed finished pipeline output — Pc, miss distance, burn options — and
 * returns prose. It computes nothing. If this panel and a physics readout
 * ever disagreed about a value, the physics readout is right by
 * construction, and the disagreement would be a bug in the AI layer worth
 * stopping for.
 * ======================================================================
 *
 * THE BADGE IS NOT DECORATION. /api/ai/advise always returns HTTP 200: when
 * no model is reachable it degrades to a deterministic rule-based advisor.
 * That text is well-written and reads exactly like model output, so without
 * the badge a viewer cannot tell which one produced it. `isLive` comes from
 * api/ai.js's strict check — only an explicit `is_fallback === false` counts
 * — so anything ambiguous shows as rule-based.
 *
 * @param {object} props
 * @param {'idle'|'running'|'done'|'error'} props.status
 * @param {import('../../api/ai.js').AiAdvisorResponse|null} props.advice
 * @param {boolean} props.isLive
 * @param {Error|null} [props.error]
 * @param {() => void} [props.onRetry]
 * @param {string} [props.awaiting] what has to happen before this can run
 */
function AiAdvisorPanel({ status, advice, isLive, error, onRetry, awaiting }) {
  if (status === 'idle') {
    return (
      <PendingRegion
        region="AI advisor"
        awaiting={awaiting ?? 'Waiting for a screened conjunction to explain.'}
      />
    )
  }

  if (status === 'running') {
    return <LoadingState label="Requesting decision support" />
  }

  if (status === 'error') {
    return (
      <ErrorState
        title="AI layer unavailable"
        detail={error?.detail ?? error?.message}
        hint="Every physics number on this screen was computed without the AI layer and is unaffected. Only the narrative is missing."
        onRetry={onRetry}
      />
    )
  }

  if (!advice) return null

  const sections = [
    ['Risk assessment', advice.risk_assessment],
    ['Recommended action', advice.recommended_action],
    ['Tradeoff analysis', advice.tradeoff_analysis],
  ].filter(([, body]) => typeof body === 'string' && body.trim().length > 0)

  return (
    <div className="ai-panel">
      <div className="ai-panel__head">
        <span
          className={`ai-panel__badge ai-panel__badge--${isLive ? 'live' : 'fallback'}`}
          title={
            isLive
              ? 'Generated by a live language model'
              : 'Generated by the deterministic rule-based advisor built into the backend — no model was reached'
          }
        >
          <span className="ai-panel__badge-dot" aria-hidden="true" />
          {isLive ? 'AI · live model' : 'AI · rule-based fallback'}
        </span>
      </div>

      {advice.executive_summary && (
        <p className="ai-panel__summary">{advice.executive_summary}</p>
      )}

      {sections.map(([title, body]) => (
        <section key={title} className="ai-panel__section">
          <h4 className="ai-panel__section-title ui-label">{title}</h4>
          <p className="ai-panel__section-body">{body}</p>
        </section>
      ))}

      <p className="ai-panel__boundary">
        Narrative only. Every figure quoted above was computed by the physics
        pipeline and is shown in the panels beside this one — the advisor is
        handed those numbers and never produces one of its own.
      </p>
    </div>
  )
}

export default AiAdvisorPanel
